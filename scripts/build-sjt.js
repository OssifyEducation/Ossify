#!/usr/bin/env node
// Build js/sjt-questions.js from content/sjt/*.json after validating every question.
// Usage: node scripts/build-sjt.js            (validate + write)
//        node scripts/build-sjt.js --check    (validate only; exit 1 on problems)
"use strict";
const fs = require("fs");
const path = require("path");
const SJT = require("../js/sjt-engine.js");
const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "content", "sjt");
const OUT = path.join(ROOT, "js", "sjt-questions.js");

const files = fs.readdirSync(DIR).filter((f) => /^sjt-\d+\.json$/.test(f)).sort();
const bank = files.map((f) => {
  const q = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  if (q.id + ".json" !== f) throw new Error(f + ": file name must match id " + q.id);
  return q;
});

const errors = SJT.validateBank(bank);
// Every reference must come from the approved, pre-verified library.
const LIB = JSON.parse(fs.readFileSync(path.join(ROOT, "content", "sjt-references.json"), "utf8"));
const approved = new Set(Object.keys(LIB).filter((k) => k[0] !== "_").map((k) => LIB[k].url));
bank.forEach((q) => (q.references || []).forEach((r) => {
  if (!approved.has(r.url)) errors.push(`${q.id}: reference not in content/sjt-references.json — ${r.url}`);
}));
const report = SJT.bankReport(bank);
console.log(`${bank.length} questions · ${report.byFormat.ranking || 0} ranking / ${report.byFormat.multiple_choice || 0} multiple choice`);
console.log("pools:", JSON.stringify(report.byPool), "attributes:", JSON.stringify(report.byAttribute));
report.warnings.forEach((w) => console.log("warning:", w));
if (errors.length) { errors.forEach((e) => console.error("error:", e)); process.exit(1); }
if (process.argv.includes("--check")) { console.log("ok"); process.exit(0); }

// Mock-pool questions are never shipped to the browser bundle (they will be served and marked by the server).
const shipped = bank.filter((q) => q.pool === "practice");
const banner = "/* GENERATED by scripts/build-sjt.js from content/sjt/*.json — do not edit by hand. */\n";
const body = "(function (root) {\n  \"use strict\";\n  var QUESTIONS = " + JSON.stringify(shipped, null, 2).replace(/\n/g, "\n  ") +
  ";\n  if (typeof module === \"object\" && module.exports) module.exports = QUESTIONS;\n  else root.OSSIFY_SJT_QUESTIONS = QUESTIONS;\n})(typeof self !== \"undefined\" ? self : this);\n";
fs.writeFileSync(OUT, banner + body);
console.log(`wrote ${path.relative(ROOT, OUT)} (${shipped.length} practice questions, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);
